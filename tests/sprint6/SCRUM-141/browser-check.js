  ok('reset disabled until identity attested', await resetButton.isDisabled());
  await page.getByRole('checkbox',{name:/Tôi đã xác minh/}).check(); await resetButton.click();
  const output = page.locator('.temporary-password'); await output.waitFor(); const temporary = await output.textContent();
  ok('admin issues random temporary password', temporary.length >= 24 && temporary !== 'Demo@12345');
  await page.locator('.password-support').scrollIntoViewIfNeeded();
  await page.screenshot({path:'admin-password-support.png',mask:[output],maskColor:'#cbd5e1'});
  await page.getByRole('button',{name:'Đã bàn giao, ẩn mật khẩu'}).click(); await output.waitFor({state:'detached'});
  ok('temporary credential hidden after handover', await output.count() === 0);
  await page.getByRole('button',{name:'Đăng xuất',exact:true}).click(); await page.waitForURL('**/login?notice=logout');
  await page.locator('#username').fill(username); await page.locator('#password').fill(temporary);
  await page.locator('.login-submit').click(); await page.waitForURL('**/change-password');
